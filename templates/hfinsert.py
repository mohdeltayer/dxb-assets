def _cover(w, h, bw, bh, fx, fy, left, top):
    """Scale and offset that cover a bw x bh box at (left, top) with a w x h image, centred on (fx, fy) in [0, 1]."""
    s = max(bw / w, bh / h)
    x = min(left, max(left + bw - w * s, left + bw / 2 - fx * w * s))
    y = min(top, max(top + bh - h * s, top + bh / 2 - fy * h * s))
    return s, x, y


