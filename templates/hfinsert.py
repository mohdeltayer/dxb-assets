def build(ins, dur, theme, work):
    """The composition folder for one insert: index.html, assets copied from uploads, the font copied in."""
    piece, d = ins['piece'], ins['data']
    if piece not in PIECES:
        raise ValueError(f'insert piece {piece!r}: only {PIECES} are allowed (advisor, 24 Oct 2026)')
    os.makedirs(os.path.join(work, 'assets'), exist_ok=True)
    os.makedirs(os.path.join(work, 'fonts'), exist_ok=True)
    shutil.copy(MARK, os.path.join(work, 'assets', 'mark.jpg'))
    fonts = os.environ.get('DUBAI_FONTS', '/root/fonts-private/dubai').rstrip('/')
    for w in ('Regular', 'Medium', 'Bold'):
        src = os.path.join(fonts, f'Dubai-{w}.ttf')
        if os.path.exists(src):
            shutil.copy(src, os.path.join(work, 'fonts'))
        else:
            print(f'hfinsert: Dubai-{w}.ttf missing, the fallback font shows (preview only)', flush=True)
    if piece == 'numbers':
        f, s = d['footage']
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', f'{s}', '-i', C.U + f, '-t', f'{dur + 1:.2f}', '-an',
                        '-vf', 'scale=1920:-2', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '18',
                        os.path.join(work, 'assets', 'bg.mp4')], check=True)
        if d.get('logo'):
            im = Image.open(C.U + d['logo']).convert('RGBA')
            im.crop(im.getbbox()).save(os.path.join(work, 'assets', 'logo.png'))
        page = numbers(d, dur, theme)
    else:
        im = Image.open(C.U + d['photo']).convert('RGB')
        im.save(os.path.join(work, 'assets', 'photo.jpg'), quality=95)
        if d.get('end'):
            Image.open(C.U + d['end']).convert('RGB').save(os.path.join(work, 'assets', 'end.jpg'), quality=95)
        page = charcard(d, dur, theme, im.size)
    open(os.path.join(work, 'index.html'), 'w', encoding='utf8').write(page)
    json.dump({'id': piece, 'name': piece}, open(os.path.join(work, 'meta.json'), 'w'))
    return work


def render(work, out, timeout):
    cli = os.environ.get('HF_CLI', 'hyperframes')
    subprocess.run([cli, 'render', work, '-o', out, '-q', 'delivery', '-f', str(FPS), '--quiet'],
                   check=True, timeout=timeout)
    return out


def overlay(video, ins, t0, dur, fade, out):
    """Lay the insert over [t0, t0 + dur] of the finished Reel, fading in and out over the crossfade; audio copied."""
    import reel
    f = f'format=yuva420p,trim=0:{dur:.3f},setpts=PTS-STARTPTS,fade=t=in:st=0:d={fade}:alpha=1,' \
        f'fade=t=out:st={dur - fade:.3f}:d={fade}:alpha=1,setpts=PTS+{t0:.3f}/TB'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', video, '-i', ins, '-filter_complex',
                    f'[1:v]{f}[ov];[0:v][ov]overlay=0:0:eof_action=pass[v]', '-map', '[v]', '-map', '0:a?',
                    '-c:a', 'copy', '-c:v', 'libx264', *reel.FINAL_ENC, '-pix_fmt', 'yuv420p', '-r', str(FPS),
                    '-movflags', '+faststart', out], check=True)
    return out


def apply(job, video, starts):
    """Every insert the job asks for, laid over the finished Reel in place. Returns one record per insert; a
    failure leaves the Reel as it was (its current card in the slot) and says why."""
    import reel
    records = []
    for ins in job.get('insert', []):
        rec = {'piece': ins.get('piece'), 'shot': ins.get('shot'), 'hf': HF_VERSION}
        t = time.time()
        work = tempfile.mkdtemp(prefix='hfins-')
        try:
            i = ins['shot']
            f = job['shots'][i][0]
            if not (f.endswith('.png') and '-gfx-' in f):
                raise ValueError(f'insert shot {i} is {f}: an insert replaces a graphic (-gfx-) shot, its fallback card')
            t0, dur = starts[i], job['shots'][i][2]
            build(ins, dur, job['theme'], os.path.join(work, 'piece'))
            left = TIMEOUT - (time.time() - t)
            if left <= 10:
                raise TimeoutError('no time left for the render')
            mp4 = render(os.path.join(work, 'piece'), os.path.join(work, 'insert.mp4'), left)
            tmp = os.path.join(work, 'reel.mp4')
            overlay(video, mp4, t0, dur, reel.X, tmp)
            shutil.move(tmp, video)
            rec.update(ok=True, at=round(t0, 2), secs=round(dur, 2))
        except Exception as e:                       # the story is never held: the current card stays
            rec.update(ok=False, error=f'{type(e).__name__}: {str(e)[:300]}')
            print(f"hfinsert: insert on shot {ins.get('shot')} failed, the current card stays: {rec['error']}", flush=True)
        finally:
            rec['render_secs'] = round(time.time() - t, 1)
            shutil.rmtree(work, ignore_errors=True)
        records.append(rec)
    return records


