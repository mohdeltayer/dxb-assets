def cover(base, name, dur, theme, key, person=None, press_at=0.25, head_secs=3.5):
    """Frame 0 to `dur`: the chip row back over the Reel (the same pixels reel.py drew), resting on frame 0 (the grid
    tile), pressing once at `press_at` (down to 94%, a small bounce, settled within 0.3 s) and fading with the
    headline over its last 0.2 s. `person` (photo, name, role, credit, focus): the kit's photo box, already open on
    frame 0 at PERSON_BOX beside the headline, stepping aside (the kit's exit) as the headline leaves at 3.5 s."""
    w = workdir('cover')
    segment(base, 0, dur, os.path.join(w, 'bg.mp4'))
    chip = json.load(open(os.path.join(CHIPS, name + '-chip.json')))
    shutil.copy(os.path.join(CHIPS, name + '-chip.png'), os.path.join(w, 'chip.png'))
    x0, y0, x1, y1 = chip['box']
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    D = f'data-start="0" data-duration="{dur:.3f}"'
    body = f"""      <video id="bg" class="clip" {D} data-media-start="0" muted src="bg.mp4"></video>
      <div class="clip" {D} style="inset:0">
        <img id="chip" src="chip.png" style="position:absolute;left:0;top:0;width:1080px;height:1920px;transform-origin:{cx:.1f}px {cy:.1f}px" />
      </div>"""
    js = f"""      tl.to('#chip', {{ scale: 0.94, y: 2, duration: 0.12, ease: 'power2.in' }}, {press_at});
      tl.to('#chip', {{ scale: 1.02, y: 0, duration: 0.1, ease: 'power2.out' }}, {press_at + 0.12:.2f});
      tl.to('#chip', {{ scale: 1, duration: 0.08, ease: 'power1.inOut' }}, {press_at + 0.22:.2f});
      tl.to('#chip', {{ opacity: 0, duration: 0.2, ease: 'none' }}, {head_secs - 0.2:.2f});"""
    css = ''
    blips = [(press_at + 0.12, 'press')]
    if person:
        photo, pname, role, credit, focus = person
        for s in (pname, role) + ((credit,) if credit else ()):
            arabic_first(s, 'person plate')
        ext = os.path.splitext(photo)[1]
        shutil.copy(photo, os.path.join(w, 'photo' + ext))
        bx, by, bw, bh = PERSON_BOX
        css = (f'      .pbox {{ left: {bx}px; top: {by}px; width: {bw}px; height: {bh}px; }}\n'
               '      .pbox .pname { font-size: 46px; } .pbox .prole { font-size: 30px; } .pbox .pcred { font-size: 21px; }\n')
        body += f"""
      <div class="pbox clip" {D}>
        <div class="pclip" id="pclip">
          <img src="photo{ext}" style="object-position: {focus[0] * 100:.0f}% {focus[1] * 100:.0f}%" />
          <div class="pshade"></div>
          <div class="pplate" id="pplate"><div class="pname">{text(pname)}</div><div class="prole">{text(role)}</div>{f'<div class="pcred">{text(credit)}</div>' if credit else ''}</div>
        </div>
        <svg width="{bw}" height="{bh}"><rect id="pframe" x="1.5" y="1.5" width="{bw - 3}" height="{bh - 3}" rx="22" pathLength="1000" stroke-dasharray="1000" stroke-dashoffset="0" /></svg>
      </div>"""
        # open on frame 0: no wipe on the cover (Mohammad, 24 Oct 2026); the kit's own exit as the headline leaves
        js = f"      gsap.set('#pclip', {{ clipPath: KIT.RECT }});\n" + js + \
             f"\n      KIT.photoBoxOut(tl, {{ box: '#pclip', frame: '#pframe', plate: '#pplate' }}, {head_secs - 0.2:.2f});"
        blips.append((head_secs - 0.16, 'wipe'))
    open(os.path.join(w, 'index.html'), 'w').write(page(body, js, dur, f':root {{ --accent: {accent(theme)}; }}\n' + css))
    return w, blips


