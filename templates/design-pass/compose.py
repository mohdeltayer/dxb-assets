def pick_headline(job, cands):
    import reel
    tmp = tempfile.mkdtemp(prefix='dp-head-')
    try:
        for h in cands:
            try:
                reel.head_layer(h, job['label'], f'{tmp}/h.png', job['source'], job['date'], job.get('country'))
                return h
            except ValueError as e:
                print(f'headline does not fit at the grid size: {h!r}: {e}', flush=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    raise ValueError('no headline candidate fits')


