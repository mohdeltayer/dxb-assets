def workdir(name):
    w = tempfile.mkdtemp(prefix=f'dp-{name}-')
    os.makedirs(os.path.join(w, 'fonts'))
    fonts = os.environ.get('DUBAI_FONTS', '/root/fonts-private/dubai')
    for wt in ('Regular', 'Medium', 'Bold'):
        src = os.path.join(fonts, f'Dubai-{wt}.ttf')
        if os.path.exists(src):
            shutil.copy(src, os.path.join(w, 'fonts'))
        else:
            print(f'compose: Dubai-{wt}.ttf missing, the fallback font shows (preview only)', flush=True)
    json.dump({'name': name}, open(os.path.join(w, 'meta.json'), 'w'))
    json.dump({}, open(os.path.join(w, 'hyperframes.json'), 'w'))
    return w


def hf_render(work, out, label, key):
    cli = os.environ.get('HF_CLI', 'hyperframes')
    t = time.time()
    subprocess.run([cli, 'render', work, '-o', out, '-q', 'delivery', '-f', str(FPS), '--quiet'], check=True, timeout=300)
    TIMES.setdefault(key, {}).setdefault('hf', []).append({'piece': label, 'render_secs': round(time.time() - t, 1)})
    shutil.rmtree(os.path.join(work, 'fonts'), ignore_errors=True)   # the font never outlives the render
    return out


def ff(*a):
    subprocess.run(['ffmpeg', '-nostdin', '-v', 'error', '-y', *a], check=True)


def segment(video, t0, dur, out):
    """The Reel's own frames for [t0, t0 + dur], frame-exact, dense keyframes so HyperFrames seeks cleanly."""
    ff('-i', video, '-ss', f'{t0:.3f}', '-t', f'{dur:.3f}', '-an', '-r', str(FPS), '-g', str(FPS), '-keyint_min',
       str(FPS), '-c:v', 'libx264', '-crf', '10', '-preset', 'veryfast', '-pix_fmt', 'yuv420p', out)
    return out


def overlay(video, ins, t0, dur, out):
    """Opaque, hard cut at each end; the Reel's audio copied (its single stretch runs under the moment)."""
    ff('-i', video, '-i', ins, '-filter_complex',
       f'[1:v]trim=0:{dur:.3f},setpts=PTS-STARTPTS+{t0:.3f}/TB[ov];[0:v][ov]overlay=0:0:eof_action=pass[v]',
       '-map', '[v]', '-map', '0:a?', '-c:a', 'copy', '-c:v', 'libx264', '-preset', 'medium', '-crf', '18',
       '-pix_fmt', 'yuv420p', '-r', str(FPS), '-movflags', '+faststart', out)
    return out


def snap(t):
    return round(t * FPS) / FPS


