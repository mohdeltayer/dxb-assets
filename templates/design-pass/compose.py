def _header(title, path):
    from PIL import Image, ImageDraw
    import fast_ar as A
    im = Image.new('RGB', (1080, 116), (20, 19, 50))
    d = ImageDraw.Draw(im)
    d.text((540, 36), title, font=A.F('Bold', 30), fill=(244, 243, 255), anchor='mm')
    d.text((270, 92), 'Published', font=A.F('Medium', 28), fill=(201, 200, 230), anchor='mm')
    d.text((810, 92), 'Design pass (pilot)', font=A.F('Medium', 28), fill=(40, 182, 246), anchor='mm')
    d.line([(540, 70), (540, 116)], fill=(63, 61, 168), width=2)
    im.save(path)
    return path


def side_by_side(left, right, out, title):
    """Published left, design pass right, each at half size under a title bar; the new version's sound."""
    hdr = _header(title, out + '.hdr.png')
    ff('-i', left, '-i', right, '-loop', '1', '-i', hdr, '-filter_complex',
       '[0:v]scale=540:960,setsar=1,fps=30[a];[1:v]scale=540:960,setsar=1,fps=30[b];[a][b]hstack=inputs=2[s];'
       '[2:v]setsar=1,fps=30[h];[h][s]vstack=inputs=2:shortest=1,format=yuv420p[v]',
       '-map', '[v]', '-map', '1:a', '-shortest', '-c:v', 'libx264', '-crf', '24', '-preset', 'medium',
       '-c:a', 'aac', '-b:a', '128k', '-movflags', '+faststart', out)
    os.remove(hdr)
    return out


def grab(video, t, out, crop=None, scale=None):
    vf = []
    if crop:
        vf.append('crop=%d:%d:%d:%d' % crop)
    if scale:
        vf.append(f'scale={scale}')
    ff('-ss', f'{t:.3f}', '-i', video, '-frames:v', '1', *(['-vf', ','.join(vf)] if vf else []), '-q:v', '3', out)
    return out


def qa(video, key, moments, end):
    q = os.path.join(OUT, 'qa')
    os.makedirs(q, exist_ok=True)
    grab(video, 0.0, f'{q}/{key}-frame0.jpg', scale='540:960')
    grab(video, 0.0, f'{q}/{key}-frame0-grid.jpg', crop=(1080, 1440, 0, 240), scale='300:400')   # phone grid size
    grab(video, 0.0, f'{q}/{key}-frame0-top.jpg', crop=(1080, 700, 0, 240))                      # chip, corner, headline
    for i, t in enumerate((0.25, 0.31, 0.37, 0.43, 0.5)):                                         # the press, frame by frame
        grab(video, t, f'{q}/.{key}-press{i}.png', crop=(560, 140, 400, 320))
    ff(*sum((['-i', f'{q}/.{key}-press{i}.png'] for i in range(5)), []), '-filter_complex', 'vstack=inputs=5',
       '-q:v', '3', f'{q}/{key}-chip-press.jpg')
    for i in range(5):
        os.remove(f'{q}/.{key}-press{i}.png')
    if 'frame_still' in moments:
        a, z = moments['frame_still']
        grab(video, (a + z) / 2, f'{q}/{key}-frame-held.jpg')
        grab(video, moments['frame'][0] + 0.3, f'{q}/{key}-frame-pressing.jpg', scale='540:960')
    if key == 'aonuma':
        grab(video, 3.0, f'{q}/{key}-box-3s.jpg', scale='540:960')
        grab(video, 3.9, f'{q}/{key}-after-box.jpg', scale='540:960')
    import decodecheck as DC
    DC.dense_strip(video, f'{q}/{key}-dense.jpg')


def combine():
    parts = [os.path.join(OUT, f'design-pass-{k}-sbs.mp4') for k in SAMPLES]
    parts = [p for p in parts if os.path.exists(p)]
    total = sum(float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p],
                                     capture_output=True, text=True).stdout) for p in parts)
    kbps = int((17.5e6 * 8 / total - 140e3) / 1000)   # under 20 MB with the sound and the container
    ins = sum((['-i', p] for p in parts), [])
    fc = ''.join(f'[{i}:v][{i}:a]' for i in range(len(parts))) + f'concat=n={len(parts)}:v=1:a=1[v][a]'
    out = os.path.join(OUT, 'design-pass-all-sbs.mp4')
    ff(*ins, '-filter_complex', fc, '-map', '[v]', '-map', '[a]', '-c:v', 'libx264', '-preset', 'medium',
       '-b:v', f'{min(kbps, 2600)}k', '-maxrate', f'{min(kbps, 2600) * 2}k', '-bufsize', f'{min(kbps, 2600) * 2}k',
       '-c:a', 'aac', '-b:a', '128k', '-movflags', '+faststart', out)
    print('combined', out, round(os.path.getsize(out) / 1e6, 2), 'MB', flush=True)


